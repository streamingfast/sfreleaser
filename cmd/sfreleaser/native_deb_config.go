package main

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strconv"
	"strings"
)

// debScripts are the maintainer scripts picked up from the packaging directory, by nfpm's
// script name.
var debScripts = []string{"preinstall", "postinstall", "preremove", "postremove"}

// debConfigOptions describes a package to generate the nfpm configuration of.
type debConfigOptions struct {
	Name        string
	Version     string
	Arch        string
	Maintainer  string
	Description string
	Homepage    string
	License     string
	Depends     []string
	Recommends  []string
	// Binary is the path of the binary, installed at '/usr/bin/<Name>'.
	Binary string
	// Dir is the packaging directory: files under its 'rootfs' directory are installed at the
	// same path from the root of the system, '<script>.sh' files are the maintainer scripts
	// ('preinstall', 'postinstall', 'preremove' and 'postremove'). Optional, may not exist.
	Dir string
}

// debContent is one file installed by the package.
type debContent struct {
	Src  string
	Dst  string
	Mode fs.FileMode
}

// debPackagingFiles lists what the packaging directory contributes: the files under 'rootfs'
// sorted by destination, and the maintainer scripts found by their nfpm script name.
func debPackagingFiles(dir string) (contents []debContent, scripts map[string]string, err error) {
	scripts = map[string]string{}
	if dir == "" {
		return nil, scripts, nil
	}

	if _, err := os.Stat(dir); os.IsNotExist(err) {
		return nil, scripts, nil
	}

	rootfs := filepath.Join(dir, "rootfs")
	if _, statErr := os.Stat(rootfs); statErr == nil {
		err = filepath.WalkDir(rootfs, func(file string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}

			if !entry.Type().IsRegular() {
				// Directories are created by the package manager, symlinks are not followed.
				return nil
			}

			info, err := entry.Info()
			if err != nil {
				return err
			}

			relative, err := filepath.Rel(rootfs, file)
			if err != nil {
				return err
			}

			contents = append(contents, debContent{
				Src:  file,
				Dst:  "/" + filepath.ToSlash(relative),
				Mode: info.Mode().Perm(),
			})
			return nil
		})
		if err != nil {
			return nil, nil, err
		}
	}

	for _, script := range debScripts {
		file := filepath.Join(dir, script+".sh")
		if info, err := os.Stat(file); err == nil && info.Mode().IsRegular() {
			scripts[script] = file
		}
	}

	return contents, scripts, nil
}

// renderNfpmConfig renders the nfpm configuration of the package. Values are written as JSON
// strings, which YAML accepts as is.
func renderNfpmConfig(options debConfigOptions) (string, error) {
	contents, scripts, err := debPackagingFiles(options.Dir)
	if err != nil {
		return "", fmt.Errorf("reading packaging directory %q: %w", options.Dir, err)
	}

	for _, content := range contents {
		if content.Dst == path.Join("/usr/bin", options.Name) {
			return "", fmt.Errorf("%q would overwrite the binary installed at %s", content.Src, content.Dst)
		}
	}

	var out strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&out, format+"\n", args...) }
	quote := strconv.Quote

	line("# Generated by sfreleaser, do not edit.")
	line("name: %s", quote(options.Name))
	line("arch: %s", quote(options.Arch))
	line("platform: linux")
	line("version: %s", quote(options.Version))
	line("section: utils")
	line("priority: optional")
	line("maintainer: %s", quote(options.Maintainer))
	if options.Description != "" {
		line("description: %s", quote(options.Description))
	}
	if options.Homepage != "" {
		line("homepage: %s", quote(options.Homepage))
	}
	if options.License != "" {
		line("license: %s", quote(options.License))
	}

	for _, list := range []struct {
		key    string
		values []string
	}{{"depends", options.Depends}, {"recommends", options.Recommends}} {
		if len(list.values) == 0 {
			continue
		}

		line("%s:", list.key)
		for _, value := range list.values {
			line("  - %s", quote(value))
		}
	}

	line("contents:")
	line("  - src: %s", quote(options.Binary))
	line("    dst: %s", quote(path.Join("/usr/bin", options.Name)))
	line("    file_info:")
	line("      mode: 0755")
	for _, content := range contents {
		line("  - src: %s", quote(content.Src))
		line("    dst: %s", quote(content.Dst))
		line("    file_info:")
		line("      mode: 0%o", content.Mode)
	}

	if len(scripts) > 0 {
		line("scripts:")
		for _, script := range debScripts {
			if file, found := scripts[script]; found {
				line("  %s: %s", script, quote(file))
			}
		}
	}

	return out.String(), nil
}
