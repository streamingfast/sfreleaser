func nativeTargetByID(id string) nativeTarget {
	for _, target := range nativeTargets {
		if target.ID == id {
			return target
		}
	}
	panic(id)
}

func Test_nativeArchiveName(t *testing.T) {
	assert.Equal(t, "firehose-core_linux_x86_64.tar.gz", nativeArchiveName("firehose-core", nativeTargetByID("linux-amd64")))
	assert.Equal(t, "firehose-core_linux_arm64.tar.gz", nativeArchiveName("firehose-core", nativeTargetByID("linux-arm64")))
	assert.Equal(t, "firehose-core_darwin_x86_64.tar.gz", nativeArchiveName("firehose-core", nativeTargetByID("darwin-amd64")))
	assert.Equal(t, "firehose-core_darwin_arm64.tar.gz", nativeArchiveName("firehose-core", nativeTargetByID("darwin-arm64")))
}

type tarFile struct {
	mode    int64
	modTime time.Time
	content string
}

func readTarGz(t *testing.T, path string) map[string]tarFile {
	t.Helper()

	file, err := os.Open(path)
	require.NoError(t, err)
	defer file.Close()

	decompressed, err := gzip.NewReader(file)
	require.NoError(t, err)

	files := map[string]tarFile{}
	reader := tar.NewReader(decompressed)
	for {
		header, err := reader.Next()
		if err == io.EOF {
			return files
		}
		require.NoError(t, err)

		content, err := io.ReadAll(reader)
		require.NoError(t, err)
		files[header.Name] = tarFile{mode: header.Mode, modTime: header.ModTime.UTC(), content: string(content)}
	}
}

func Test_packageNativeArchives(t *testing.T) {
	root := t.TempDir()
	t.Chdir(root)

	require.NoError(t, os.WriteFile("README.md", []byte("readme"), 0o644))
	require.NoError(t, os.WriteFile("LICENSE", []byte("license"), 0o644))
	for _, id := range []string{"linux-amd64", "darwin-arm64"} {
		require.NoError(t, os.MkdirAll(filepath.Join("dist", id), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join("dist", id, "acme"), []byte("binary "+id), 0o755))
	}

	modTime := time.Date(2026, 10, 28, 12, 0, 0, 0, time.UTC)
	options := nativePackageOptions{
		Project: "acme-project",
		Binary:  "acme",
		Binaries: map[string]string{
			"linux-amd64":  filepath.Join("dist", "linux-amd64", "acme"),
			"darwin-arm64": filepath.Join("dist", "darwin-arm64", "acme"),
		},
		Files:     []string{"README.md", "LICENSE"},
		ModTime:   modTime,
		OutputDir: "out",
	}

	archives, err := packageNativeArchives(options)
	require.NoError(t, err)
	require.Len(t, archives, 2)

	assert.Equal(t, "acme-project_darwin_arm64.tar.gz", archives[0].Name)
	assert.Equal(t, "acme-project_linux_x86_64.tar.gz", archives[1].Name)

	assert.Equal(t, map[string]tarFile{
		"acme":      {mode: 0o755, modTime: modTime, content: "binary linux-amd64"},
		"README.md": {mode: 0o644, modTime: modTime, content: "readme"},
		"LICENSE":   {mode: 0o644, modTime: modTime, content: "license"},
	}, readTarGz(t, filepath.Join("out", "acme-project_linux_x86_64.tar.gz")))

	again, err := packageNativeArchives(options)
	require.NoError(t, err)
	assert.Equal(t, archives[1].SHA256, again[1].SHA256, "packaging the same files twice gives the same archive")

	require.NoError(t, writeChecksums(filepath.Join("out", "checksums.txt"), []nativeArchive{archives[1], archives[0]}))
	checksums, err := os.ReadFile(filepath.Join("out", "checksums.txt"))
	require.NoError(t, err)
	assert.Equal(t,
		archives[0].SHA256+"  acme-project_darwin_arm64.tar.gz\n"+archives[1].SHA256+"  acme-project_linux_x86_64.tar.gz\n",
		string(checksums),
	)
}

