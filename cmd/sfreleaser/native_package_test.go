// Test_renderBrewFormula compares against the formula Goreleaser generated for
// dummy-blockchain v1.7.10, only the "generated by" line differs.
func Test_renderBrewFormula(t *testing.T) {
	global := &GlobalModel{Owner: "streamingfast", Project: "dummy-blockchain", Binary: "dummy-blockchain", License: "Apache-2.0"}
	archive := func(id, sha string) nativeArchive {
		target := nativeTargetByID(id)
		return nativeArchive{Target: target, Name: nativeArchiveName(global.Project, target), SHA256: sha}
	}

	formula, err := renderBrewFormula(global, "v1.7.10", []nativeArchive{
		archive("darwin-amd64", "fd9d613865fc41086606561271948ba8d92b70eba930e1d8963cd5cdcc06eea3"),
		archive("darwin-arm64", "185864eec68a0540fcfeda42b73476959160a6008b160f2d245b32848942e590"),
		archive("linux-amd64", "35b62ec6b8dab482d0388c09bcba8be1bf46d66000e718d261cb4d6ffb56c70d"),
		archive("linux-arm64", "d70e2aa1bef6bfb9c09e7a9237ad618625dd3c75da6ef348da7094917eb9cd3b"),
	})
	require.NoError(t, err)

	expected, err := os.ReadFile(filepath.Join("testdata", "native", "dummy-blockchain.golden.rb"))
	require.NoError(t, err)
	assert.Equal(t, string(expected), formula)
}

func Test_renderBrewFormula_noLicense(t *testing.T) {
	global := &GlobalModel{Owner: "streamingfast", Project: "acme", Binary: "acme"}
	target := nativeTargetByID("linux-amd64")

	formula, err := renderBrewFormula(global, "v1.0.0", []nativeArchive{{Target: target, Name: nativeArchiveName("acme", target), SHA256: "abc"}})
	require.NoError(t, err)
	assert.NotContains(t, formula, "license")
	assert.Contains(t, formula, "  version \"1.0.0\"\n\n  on_linux do\n")
	assert.NotContains(t, formula, "on_macos")
}

